"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm"),path=require("node:path");
const scope={};vm.runInNewContext(fs.readFileSync(path.join(__dirname,"..","shop-rotation.js"),"utf8"),scope);
const api=scope.AutoTypeShopRotation;
const catalog=["title","banner","frame","trail","arena","result"].flatMap(slot=>Array.from({length:5},(_,i)=>({id:slot+"_"+i,slot,price:100+i})));
const sets=[{id:"z-set",items:[1]},{id:"a-set",items:[2]}];
const first=api.rotate("2026-10-08",catalog,sets),second=api.rotate("2026-10-09",catalog,sets);
assert.equal(first.items.length,6);
assert.equal(new Set(first.items.map(item=>item.id)).size,6);
assert.notEqual(first.items.map(x=>x.id).join(","),second.items.map(x=>x.id).join(","));
assert.equal(first.items.map(x=>x.id).join(","),api.rotate("2026-10-08",catalog,sets).items.map(x=>x.id).join(","));
assert.notEqual(first.featured.id,second.featured.id);
assert.equal(api.ZONE,"America/New_York");
assert.equal(api.dayKey(new Date("2026-10-08T03:59:59Z")),"2026-10-07");
assert.equal(api.dayKey(new Date("2026-10-08T04:00:00Z")),"2026-10-08");
assert.equal(api.nextReset(new Date("2026-10-08T03:59:59Z")).toISOString(),"2026-10-08T04:00:00.000Z");
assert.equal(api.countdown(new Date("2026-10-08T03:59:00Z")),"00:01:00");
assert.equal(api.nextReset(new Date("2026-01-14T17:00:00Z")).toISOString(),"2026-01-15T05:00:00.000Z");
assert.equal(api.nextReset(new Date("2026-07-14T17:00:00Z")).toISOString(),"2026-07-15T04:00:00.000Z");
assert.equal(api.nextReset(new Date("2026-03-08T05:00:00Z")).toISOString(),"2026-03-09T04:00:00.000Z");
assert.equal(api.nextReset(new Date("2026-11-01T04:00:00Z")).toISOString(),"2026-11-02T05:00:00.000Z");
assert.ok(api.itemAvailable(first.items[0].id,catalog,new Date("2026-10-08T12:00:00Z")));
assert.ok(api.collectionAvailable(first.featured.id,sets,new Date("2026-10-08T12:00:00Z")));
assert.ok(!api.itemAvailable("unknown",catalog,new Date("2026-10-08T12:00:00Z")));
assert.equal(api.rotate("2026-10-08",[],[]).items.length,0);
console.log("Shop rotation regression PASSED (six offers, Eastern midnight, DST, offer matching).");
